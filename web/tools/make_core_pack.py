#!/usr/bin/env python3
"""Converts the built-in scenes (art/scenes.json, written by build_assets.py) into the 'Luciel Core' visual pack in the
public pack format (packs/luciel-core/pack.json) plus a pack.js wrapper so it also loads from file:// pages.
File paths in the core pack are relative to the app root (it is the only pack allowed to do that)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(os.path.join(ROOT, 'art/scenes.json')))
scenes = []
for s in src['scenes']:
    kind = s['kind']
    bg = {'image': s['image']}
    if s.get('video'): bg['video'] = s['video']
    if s.get('px') and s['px'] != s['image']: bg['pixel'] = s['px']
    if kind == 'video':
        bg['loopBpm'] = s.get('loopBpm', 120)
        if s.get('still'): bg['motion'] = 'drift'
    if s.get('loopDuration'): bg['loopDuration'] = s['loopDuration']
    if s.get('hasCharacter'): bg['featuresCharacter'] = True
    o = {'id': s['id'], 'name': s['name'], 'thumb': s['thumb'], 'background': bg}
    if kind == 'pixel': o['pixel'] = True
    if s.get('palette'): o['themeDefault'] = s['palette']
    o['particles'] = s.get('particles', [])
    ch = {'use': 'lucielle', 'poses': s.get('poses') or ['music']}
    if s.get('dance'): ch['tier'] = s['dance']
    o['character'] = ch
    if s.get('style'): o['effects'] = [{'type': s['style'], 'intensity': 1}]
    m = {'genres': s.get('genres', []), 'moods': s.get('moods', [])}
    if s.get('coverGenres'): m['coverGenres'] = s['coverGenres']
    if s.get('energy'): m['energy'] = s['energy']
    if s.get('bpm'): m['bpm'] = s['bpm']
    if s.get('skin'): m['skins'] = [s['skin']]
    o['match'] = m
    scenes.append(o)
pack = {'format': 'luciel-pack/1', 'id': 'luciel-core', 'name': 'Luciel Core', 'author': 'Luciel', 'version': '1.0.1',
        'description': 'The built-in Lucielle scenes: genre stages, mood scenes, pixel stages for the Classic skin and the cyber / datamosh / dither loops.',
        'preview': 'icons/icon-512.png', 'builtin': True, 'scenes': scenes}
d = os.path.join(ROOT, 'packs/luciel-core'); os.makedirs(d, exist_ok=True)
txt = json.dumps(pack, indent=1, ensure_ascii=False)
open(os.path.join(d, 'pack.json'), 'w').write(txt + '\n')
open(os.path.join(d, 'pack.js'), 'w').write('/* Generated by tools/make_core_pack.py from art/scenes.json - the built-in scenes as a standard Luciel visual pack (see PACKS.md). */\nwindow.LUCIEL_CORE_PACK = ' + txt + ';\n')
print('core pack:', len(scenes), 'scenes')
