const { chromium } = require('/workspace/pwtest/node_modules/playwright-core');
const fs = require('fs'), path = require('path');
const MEDIA = path.resolve(__dirname, 'media');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--no-sandbox'] });
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ' ' + m.text()); });
  page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
  page.on('requestfailed', (r) => { if (!r.url().startsWith('blob:')) errors.push('REQFAIL ' + r.url()); });
  page.on('response', (r) => { if (r.status() >= 400) errors.push('HTTP ' + r.status() + ' ' + r.url()); });
  await page.goto('http://localhost:8765/', { waitUntil: 'networkidle' });
  await page.evaluate(() => { localStorage.clear(); return new Promise(r => { const q = indexedDB.deleteDatabase('luciel'); q.onsuccess = q.onerror = q.onblocked = () => r(); }); });
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForTimeout(800);
  await page.screenshot({ path: '/tmp/luc/s-empty.png' });
  const files = fs.readdirSync(MEDIA).sort().map((f) => path.join(MEDIA, f));
  await page.setInputFiles('#fileInput', files);
  await page.waitForFunction(() => window.AeroAmp.tracks.length === 8, null, { timeout: 30000 });
  await page.waitForTimeout(1500);
  await page.evaluate(() => { const A = window.AeroAmp; A.playTrack(A.tracks[2]); A.engine.audio.currentTime = 6; });
  await page.waitForTimeout(5000);
  console.log(await page.evaluate(() => { const A = window.AeroAmp; return { scene: A.luciel.scene && A.luciel.scene.id, tier: A.luciel.st.tier, bpm: A.tracker.bpm, src: A.tracker.source, infos: A.tracks.map(t => t.name + ':' + (t.bpmInfo ? t.bpmInfo.bpm + '/' + t.bpmInfo.source : '-')) }; }));
  await page.screenshot({ path: '/tmp/luc/s-aero.png' });
  await page.evaluate(() => window.AeroAmp.applyTheme('red', 'classic'));
  await page.waitForTimeout(1500);
  await page.screenshot({ path: '/tmp/luc/s-classic.png' });
  console.log('errors', errors);
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
